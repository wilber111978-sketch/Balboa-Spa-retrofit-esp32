#!/usr/bin/env python3
"""Deterministically gzip the static UI into flash arrays; no filesystem upload."""
from pathlib import Path
import gzip,hashlib
root=Path(__file__).resolve().parents[1]
out=root/'firmware/libraries/SpaLiveApi/src/WebAssets.h'
files=sorted(p for p in (root/'firmware/data').iterdir() if p.is_file() and p.name!='runtime.js')
lines=['#pragma once','#include <cstdint>','#include <cstddef>','// Generated by tools/embed-assets.py. Do not hand-edit.']
records=[]
for i,p in enumerate(files):
 data=gzip.compress(p.read_bytes(),compresslevel=9,mtime=0);name=f'spa_asset_{i}'
 lines += [f'// {p.name}: SHA256 {hashlib.sha256(p.read_bytes()).hexdigest()}',f'static const uint8_t {name}[] = {{']
 lines += [','.join(str(b) for b in data[n:n+32])+',' for n in range(0,len(data),32)]
 lines += ['};']
 mime={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8'}[p.suffix]
 records.append(f'{{"/{p.name}","{mime}",{name},sizeof({name})}}')
lines+=['struct SpaAsset { const char *path; const char *type; const uint8_t *data; size_t size; };','static const SpaAsset spaAssets[] = {',',\n'.join(records),'};','']
out.write_text('\n'.join(lines));print(f'Embedded {len(files)} files; {sum(len(gzip.compress(p.read_bytes(),mtime=0)) for p in files)} gzip bytes')
